"""Shared data shapes passed between packages. Data only, no behaviour."""

from datetime import datetime
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class Chunk(BaseModel):
    """Data shape for a raw code or text chunk."""

    model_config = ConfigDict(frozen=True)

    id: str
    url: str
    anchor: str
    title: str
    header_path: tuple[str, ...]
    text: str
    source_path: str
    start_line: int


class ScoredChunk(BaseModel):
    """Data shape for a chunk enriched with stage-by-stage retrieval scores."""

    model_config = ConfigDict(frozen=True)

    chunk: Chunk
    bm25_rank: int | None = None
    bm25_score: float | None = None
    dense_rank: int | None = None
    dense_score: float | None = None
    rrf_score: float | None = None
    rerank_score: float | None = None


class Citation(BaseModel):
    """Data schema for numbered citations embedded in answer text."""

    model_config = ConfigDict(frozen=True)

    number: int
    chunk_id: str
    url: str
    title: str


class SentenceSupport(BaseModel):
    """Support verification details for an individual sentence in an answer."""

    model_config = ConfigDict(frozen=True)

    sentence: str
    cited_chunk_ids: list[str]
    label: Literal["supported", "partial", "unsupported"]
    score: float


class Answer(BaseModel):
    """Final output response generated by the system."""

    model_config = ConfigDict(frozen=True)

    text: str
    citations: list[Citation]
    abstained: bool
    confidence: float = Field(ge=0, le=1)
    groundedness: float = Field(ge=0, le=1)
    cache_tier: Literal["exact", "semantic"] | None = None
    timings: dict[str, float] = Field(default_factory=dict)
    trace_id: str
    index_version: str
    prompt_version: str


class ExplanationTrace(BaseModel):
    """Full execution trace explaining how an answer was derived."""

    model_config = ConfigDict(frozen=True)

    trace_id: str
    question: str
    standalone_question: str
    candidates: list[ScoredChunk]
    used_chunk_ids: list[str]
    sentences: list[SentenceSupport]
    abstain_reason: str | None = None
    timings: dict[str, float] = Field(default_factory=dict)
    versions: dict[str, str] = Field(default_factory=dict)


class StreamEvent(BaseModel):
    """Event payload emitted during SSE streaming responses."""

    model_config = ConfigDict(frozen=True)

    type: Literal["retrieval", "token", "citations", "groundedness", "done", "error"]
    data: Any


class RequestSignals(BaseModel):
    """Telemetry metrics recorded per request for monitoring and drift tracking."""

    model_config = ConfigDict(frozen=True)

    trace_id: str
    timestamp: datetime
    query: str
    retrieval_mode: str
    latency_ms: float
    cache_tier: Literal["exact", "semantic"] | None = None
    abstained: bool
    groundedness: float = Field(ge=0, le=1)
    top_score: float | None = None
    ttft_ms: float | None = None
    error: str | None = None
